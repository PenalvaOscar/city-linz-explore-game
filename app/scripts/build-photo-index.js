#!/usr/bin/env node
// Generates src/data/photos.ts from ../data/photos/*.jpg so Metro can bundle every
// spot photo with a static require. Re-run after adding or renaming a photo.
const fs = require('fs');
const path = require('path');

const photosDir = path.resolve(__dirname, '../../data/photos');
const outFile = path.resolve(__dirname, '../src/data/photos.ts');

const files = fs
  .readdirSync(photosDir)
  .filter((f) => /\.(jpe?g|png)$/i.test(f))
  .sort();

for (const f of files) {
  if (!/^[a-z0-9-]+\.(jpe?g|png)$/.test(f)) {
    console.error(`Photo file name "${f}" must be an ASCII slug (lowercase letters, digits, hyphens).`);
    process.exit(1);
  }
}

const lines = files.map((f) => `  '${f}': require('../../../data/photos/${f}'),`);
const out = `// GENERATED by scripts/build-photo-index.js. Do not edit; re-run "npm run build:photos".
export const photos: Record<string, number> = {
${lines.join('\n')}
};
`;
fs.writeFileSync(outFile, out);
console.log(`Wrote ${path.relative(process.cwd(), outFile)} with ${files.length} photo(s).`);
